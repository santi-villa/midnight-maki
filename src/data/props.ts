/** Static world props (not part of the decoration catalog). Footprint in tiles, sprite in px. */
export interface PropDef {
  kind: string;
  c1: string;
  c2: string;
  w: number;
  h: number;
  sw: number; // sprite width px
  sh: number; // sprite height px
  solid: boolean;
  /** Flat scenery under actors; it does not cast a standing object's shadow. */
  ground?: boolean;
  variant?: number;
  light?: string;
  /** look of the restaurant facade: 0 inherited .. 3 heart of the village (see restaurant/stages.ts) */
  stage?: number;
  anim?: 'sway' | 'flicker' | 'water';
  /** text painted on the sprite (shop plaques, signposts) */
  label?: string;
}

